export function normalizeLanguage(lang) {
  if (!lang) return "English";
  if (lang.includes("Hindi") || lang.includes("हिन्दी")) return "Hindi";
  if (lang.includes("Bengali") || lang.includes("বাংলা")) return "Bengali";
  return "English";
}

export function getTranslation(rawLang, key) {
  const lang = normalizeLanguage(rawLang);
  const selected = translations[lang] || translations["English"];
  return selected[key] || translations["English"][key] || key;
}
